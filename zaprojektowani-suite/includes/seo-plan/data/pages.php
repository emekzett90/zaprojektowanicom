<ul><li>liczby sekcji i podstron,</li><li>tego, czy masz gotowe teksty i zdjęcia, czy przygotowujemy je razem z projektem,</li><li>dodatków, takich jak rezerwacje online, wersja językowa albo galeria realizacji.</li></ul>
<p>Typowy projekt trwa od 2 do 4 tygodni. Prostą wizytówkę z gotowymi materiałami da się opublikować bliżej dolnej granicy. Dokładną wycenę strony wizytówki dla firmy przygotujemy po wypełnieniu <a class="zpSeoLink" href="/studio-wyceny/">Studia Wyceny</a>, a ogólne zasady wyceny opisujemy w poradniku <a class="zpSeoLink" href="/strony-www/ile-kosztuje-stworzenie-strony-internetowej-dla-firmy/">ile kosztuje strona internetowa</a>.</p>
<h2 id="kreator-czy-projekt-od-podstaw">Kreator czy projekt od podstaw</h2>
<p>Kreatory stron pozwalają zbudować wizytówkę samodzielnie, ale wybierasz wtedy gotowy szablon, piszesz teksty sam i zwykle płacisz abonament za platformę. Projekt od podstaw kosztuje więcej na starcie, za to strona wygląda jak Twoja marka, a nie jak setki innych, teksty odpowiadają na pytania klientów, a strona działa na Twojej domenie. Plusy i minusy obu modeli opisaliśmy w tekście <a class="zpSeoLink" href="/strony-internetowe/strona-na-abonament-czy-na-wlasnosc/">strona na abonament czy na własność</a>.</p>
